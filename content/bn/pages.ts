const BN_DIGITS = "০১২৩৪৫৬৭৮৯";

/** 3500 → "৩,৫০০" */
export function toBnNumber(value: number | string): string {
  const text = typeof value === "number" ? value.toLocaleString("en-US") : value;
  return text.replace(/\d/g, (d) => BN_DIGITS[Number(d)]);
}

/** 3500 → "৳৩,৫০০" */
export function bnTaka(value: number): string {
  return `৳${toBnNumber(value)}`;
}

